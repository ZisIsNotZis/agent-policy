#!/usr/bin/env python3
"""One tool: check AGENTS.yaml, then write the role views.

    python3 tools/policy.py [--depth N]

The tree is a forest of top-level fact nodes. A fact carries `_fact`; a goal or
practice carries `_goal`. `_who` is inherited from the nearest ancestor that
declares it; a node under no `_who` is not rendered. The check covers the schema,
the global names, the references, the banned words and duplicate triggers; an
unlinked reference is information, not an error, and a reference that resolves
but is not in a role's view is reported as information naming that role.

The views are the nodes whose `_who` names the role, written to `agents/<role>.md`
and the zh views to `/tmp/agent-policy/zh/<role>.md`. Each view carries the
generator banner and the path of a node whose parent is not in the view.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "AGENTS.yaml"
SCHEMA = ROOT / "AGENTS.schema.yaml"
ROLES = ROOT / "roles.yaml"
BANNED = ROOT / "banned.yaml"
OUT = ROOT / "agents"
OUT_ZH = Path("/tmp/agent-policy/zh")
BANNER = "<!-- generated by tools/policy.py from AGENTS.yaml; do not edit -->"


class Strict(yaml.SafeLoader):
    """A loader that refuses a duplicate key instead of silently keeping the last one."""


def _mapping(loader, node, deep=False):
    seen = set()
    for key_node, _ in node.value:
        key = loader.construct_object(key_node, deep=deep)
        if key in seen:
            raise SystemExit(f"duplicate key {key!r}")
        seen.add(key)
    return yaml.SafeLoader.construct_mapping(loader, node, deep=deep)


Strict.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _mapping)


def load(path: Path):
    return yaml.load(path.read_text(encoding="utf-8"), Loader=Strict)


def is_text(value, bilingual: bool) -> bool:
    if bilingual:
        return (
            isinstance(value, dict)
            and set(value) == {"en", "zh"}
            and all(isinstance(value.get(lang), str) and value[lang].strip() for lang in ("en", "zh"))
        )
    return isinstance(value, str) and value.strip() != ""


def text_of(value, lang: str, bilingual: bool) -> str:
    if bilingual:
        return value.get(lang, "") if isinstance(value, dict) else ""
    return value if isinstance(value, str) else ""


def walk(nodes: list, index: dict, keys: dict, node: dict, path: list[str]):
    for key, value in node.items():
        if key.startswith("_") or not isinstance(value, dict):
            continue
        full = ".".join(path + [key])
        nodes.append((path + [key], value))
        index[full] = value
        keys.setdefault(key, full)
        walk(nodes, index, keys, value, path + [key])


def collect():
    corpus = load(CORPUS)
    nodes: list = []
    index: dict = {}
    keys: dict = {}
    walk(nodes, index, keys, corpus, [])
    return corpus, nodes, index, keys


def resolve(ref: str, index: dict, keys: dict) -> str | None:
    if ref in index:
        return ref
    if ref in keys:
        return keys[ref]
    return None


def effective_who(index: dict, path: list[str]) -> list[str]:
    """The nearest ancestor's `_who`, or the node's own when it declares one."""
    for i in range(len(path), 0, -1):
        node = index[".".join(path[:i])]
        if node.get("_who"):
            return list(node["_who"])
    return []


def banned_pattern(term: str) -> re.Pattern:
    parts = [re.escape(p) for p in re.split(r"[-_ ]+", term.strip())]
    body = r"[-_ ]".join(parts)
    return re.compile(rf"(?<![A-Za-z]){body}(?:s|es)?(?![A-Za-z])", re.I)


def check(corpus: dict, spec: dict, roles: dict, banned: list[str]):
    text = set(spec["text_fields"])
    list_fields = set(spec["list_fields"])
    comment = spec["comment_field"]
    forbidden = set(spec["forbidden"])
    bilingual = bool(spec.get("bilingual", False))
    required_any = spec.get("node_required_any", ["_goal"])
    all_roles = set(roles)
    fails: list[str] = []
    infos: list[str] = []
    _, nodes, index, keys = collect()
    seen: dict[str, str] = {}
    triggers: dict[str, str] = {}
    patterns = [(term, banned_pattern(term)) for term in banned]

    # `_other_parents` must not form a cycle with the tree.
    def ancestors(path: list[str]):
        for i in range(1, len(path) + 1):
            yield ".".join(path[:i])

    for path, node in nodes:
        full = ".".join(path)
        key = path[-1]
        if key in seen:
            fails.append(f"{full}: duplicate name {key!r} (also {seen[key]})")
        seen[key] = full
        for field in node:
            if field.startswith("_") and field not in text | list_fields | {comment}:
                fails.append(f"{full}: field {field}")
        for field in forbidden:
            if field in node:
                fails.append(f"{full}: forbidden {field}")
        if not any(field in node for field in required_any):
            fails.append(f"{full}: no {' or '.join(required_any)}")
        for field in text:
            if field not in node:
                continue
            value = node[field]
            if not is_text(value, bilingual):
                fails.append(f"{full}.{field}: not non-empty text")
                continue
            for lang in (("en", "zh") if bilingual else ("en",)):
                body = text_of(value, lang, bilingual)
                for term, pattern in patterns:
                    if pattern.search(body):
                        fails.append(f"{full}.{field}.{lang}: banned {term!r}")
        if "_how" in node and "_goal" not in node:
            fails.append(f"{full}._how: no _goal")
        if "_know" in node and "_how" not in node:
            fails.append(f"{full}._know: no _how")
        who = effective_who(index, path)
        if "_who" in node:
            declared = node["_who"]
            if not isinstance(declared, list) or not all(isinstance(r, str) for r in declared):
                fails.append(f"{full}._who: not a list of role names")
        for role in who:
            if role not in all_roles:
                fails.append(f"{full}._who: unknown role {role!r}")
        if who and "_goal" not in node:
            fails.append(f"{full}._who: rendered node has no _goal")
        if "_when" in node:
            trigger = text_of(node["_when"], "en", bilingual)
            if trigger:
                if trigger in triggers:
                    fails.append(f"{full}._when: duplicate trigger {trigger!r} (also {triggers[trigger]})")
                else:
                    triggers[trigger] = full
        for field in list_fields - {"_who"}:
            if field in node:
                refs = node[field]
                if not isinstance(refs, list) or not all(isinstance(r, str) for r in refs):
                    fails.append(f"{full}.{field}: not a list of strings")
                    continue
                for ref in refs:
                    target = resolve(ref, index, keys)
                    if target is None:
                        infos.append(f"{full}.{field}: {ref!r} is not linked")
                    elif field == "_other_parents" and target in set(ancestors(path)):
                        fails.append(f"{full}._other_parents: {ref!r} is its own ancestor")
        if comment in node:
            value = node[comment]
            if isinstance(value, str):
                pass
            elif isinstance(value, dict) and set(value) == {"why", "recheck_when"}:
                if not all(isinstance(v, str) and v.strip() for v in value.values()):
                    fails.append(f"{full}.{comment}: why and recheck_when must be non-empty text")
            else:
                fails.append(f"{full}.{comment}: text or {{why, recheck_when}}")
            infos.append(f"{full}.{comment}: recorded exception")
        if "_how" in node:
            how = text_of(node["_how"], "en", bilingual)
            if how and not re.search(r"(^|\n)\s*\d\.", how) and not re.search(r"`[^`]+`", how):
                infos.append(f"{full}._how: no numbered step and no named file or command")
        for term, pattern in patterns:
            if pattern.search(key.replace("_", " ")):
                fails.append(f"{full}: node name is banned {term!r}")
    return fails, infos


def rule_text(node: dict, lang: str = "en") -> str:
    """The role's formatter: `when -> goal. how`, lowercased at the head."""
    def get(field: str) -> str:
        value = node.get(field)
        if isinstance(value, dict):
            return (value.get(lang) or value.get("en") or "").strip()
        return value.strip() if isinstance(value, str) else ""

    def lower(value: str) -> str:
        return value[:1].lower() + value[1:] if value[:1].isupper() and not value.isupper() else value

    when, goal, how = get("_when"), get("_goal"), get("_how")
    if not goal:
        return ""
    head = lower(when.rstrip(".。")) + " → " if when else ""
    body = lower(goal.rstrip(".。")) + ". "
    if how:
        body += how.rstrip(".。") + "."
    return (head + body).rstrip()


def view_set(role: str, depth: int, corpus: dict, index: dict, keys: dict, nodes: list):
    """Members of the view, in source order, plus the `_depends_on` closure at depth."""
    included = {".".join(path) for path, node in nodes if role in effective_who(index, path)}
    for _ in range(depth):
        added = set()
        for full in included:
            for ref in index[full].get("_depends_on") or []:
                target = resolve(ref, index, keys)
                if target and target not in included:
                    added.add(target)
        included |= added
    return included


def render(role: str, lang: str, depth: int, corpus: dict, roles: dict) -> str:
    _, nodes, index, keys = collect()
    included = view_set(role, depth, corpus, index, keys, nodes)
    order = [".".join(path) for path, _ in nodes if ".".join(path) in included]
    inc = set(order)

    def parent_of(full: str) -> str | None:
        parts = full.split(".")
        for i in range(len(parts) - 1, 0, -1):
            candidate = ".".join(parts[:i])
            if candidate in inc:
                return candidate
        return None

    children: dict[str | None, list[tuple[str, bool]]] = {}
    for full in order:
        children.setdefault(parent_of(full), []).append((full, False))
    for full in order:
        for ref in index[full].get("_other_parents") or []:
            target = resolve(ref, index, keys)
            if target in inc and target != parent_of(full):
                children.setdefault(target, []).append((full, True))

    title = "法，{role} 读到的样子" if lang == "zh" else "Law, as {role} reads it"
    out = [f"# {title.format(role=role)}\n\n", f"{BANNER}\n\n", f"{roles[role].get('description','')}\n"]
    seen_lines: set[str] = set()
    emitted: list[tuple[int, str, dict]] = []

    def emit(full: str, level: int, extra: bool, stack: tuple[str, ...]):
        if full in stack:
            raise SystemExit(f"_other_parents cycle at {full}")
        if extra and full in [f for _, f, _ in emitted]:
            return
        node = index[full]
        refs = " ".join("@" + r for r in (node.get("_depends_on") or []) if resolve(r, index, keys) in inc)
        roots = " ".join("^" + r for r in (node.get("_other_parents") or []) if resolve(r, index, keys))
        refs = " ".join(part for part in (refs, roots) if part)
        label = full.split(".")[-1]
        if not extra and parent_of(full) is None and "." in full:
            label = ".".join(full.split(".")[-2:])
        if extra:
            home = parent_of(full) or ""
            label += f" (see {home})"
        line = f"{'  ' * level}**{label}.** {rule_text(node, lang)}"
        out.append((line + " " + refs).rstrip() + "\n")
        emitted.append((level, full, node))
        if extra:
            return
        for child, is_extra in children.get(full, []):
            emit(child, level + 1, is_extra, stack + (full,))

    for full, is_extra in children.get(None, []):
        emit(full, 0, is_extra, ())
    return "".join(out)


def frontmatter(role: str, spec: dict) -> str:
    if role == "root_manager":
        return ""
    desc = str(spec.get("description", "")).replace('"', "'")
    return "\n".join([
        "---",
        f"name: {role}",
        f'description: "{desc}"',
        f"tools: {spec.get('tools', '')}",
        f"thinking: {spec.get('thinking', '')}",
        "model: inherit",
        "systemPromptMode: replace",
        "inheritProjectContext: false",
        "inheritGlobalContext: false",
        "inheritSkills: false",
        "---",
        "",
        "",
    ])


def write_views(depth: int) -> None:
    roles = load(ROLES)
    for role, spec in roles.items():
        path = OUT / f"{role}.md"
        path.parent.mkdir(exist_ok=True)
        path.write_text(frontmatter(role, spec) + render(role, "en", depth, load(CORPUS), roles),
                        encoding="utf-8")
        zh = OUT_ZH / f"{role}.md"
        zh.parent.mkdir(parents=True, exist_ok=True)
        zh.write_text(frontmatter(role, spec).replace("inherit", "inherit") + render(role, "zh", depth, load(CORPUS), roles),
                      encoding="utf-8")
    for stale in OUT.glob("*.md"):
        if stale.stem not in roles:
            stale.unlink()


def usage(code: int, message: str = "") -> int:
    if message:
        print(message, file=sys.stderr)
    print("usage: python3 tools/policy.py [--depth N]", file=sys.stderr)
    return code


def main() -> int:
    args = sys.argv[1:]
    depth = 0
    if args:
        if args[0] != "--depth" or len(args) > 2:
            return usage(2, f"unknown option {args[0]!r}")
        if len(args) != 2 or not re.fullmatch(r"\d+", args[1]):
            return usage(2, "--depth needs a number")
        depth = int(args[1])
    spec = load(SCHEMA)
    roles = load(ROLES)
    banned = (load(BANNED) or {}).get("banned") or []
    corpus = load(CORPUS)

    fails, infos = check(corpus, spec, roles, banned)
    classes: dict[str, list[str]] = {}
    for line in infos:
        where, _, message = line.partition(": ")
        classes.setdefault(message, []).append(where)
    for message, places in classes.items():
        print(f"info: {len(places)} - {message}")
        for place in places[:4]:
            print(f"info:   {place}")
        if len(places) > 4:
            print(f"info:   ... {len(places) - 4} more")
    if fails:
        print("\n".join("FAIL " + line for line in fails))
        return 1

    write_views(depth)
    print(f"ok: {len(roles)} roles; zh views in {OUT_ZH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
